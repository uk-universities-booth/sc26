#!/usr/bin/env python3
"""Convert the programme spreadsheet (CSV export) into Jekyll data files.

Usage:  python scripts/csv_to_data.py courses-info.csv
Writes: _data/courses/<university-id>.yml   (one file per university)
Re-run whenever the spreadsheet changes. Output is plain YAML, no dependencies.
"""
import csv, json, re, sys
from pathlib import Path

# keyword found in the "University name" cell -> id used in _data/universities.yml
UNI_IDS = {"university college london": "ucl", "ucl": "ucl", "imperial": "imperial",
           "queen mary": "qmul", "queen's": "belfast", "durham": "durham", "leeds": "leeds",
           "manchester": "manchester", "warwick": "warwick", "sheffield": "sheffield",
           "birmingham": "birmingham", "cardiff": "cardiff", "oxford": "oxford"}
QUAL = {"msc": "MSc", "mres": "MRes", "phd": "PhD", "pgdip": "PGDip", "pgcert": "PGCert", "pga": "PGA"}
TYPOS = {"Weednesday": "Wednesday", "Sepetmber": "September"}
SKIP_HOSTS = ("sharepoint.com", "onedrive")  # private file-share links, not public pages

def clean(s):
    s = (s or "").replace("\u202f", " ").replace("\u00a0", " ").strip()
    for a, b in TYPOS.items():
        s = s.replace(a, b)
    return re.sub(r"[ \t]+", " ", s)

def split_list(s, sep=";"):
    seen, out = set(), []
    for p in clean(s).split(sep):
        p = p.strip().rstrip(".") if sep == ";" else p.strip()
        if p and p.lower() not in seen:
            seen.add(p.lower()); out.append(p)
    return out

def bullets(s):
    return [re.sub(r"^[-*•]\s*", "", l.strip()) for l in clean(s).splitlines() if l.strip(" -*•")]

def url(s):
    s = clean(s)
    return s if s.startswith("http") and not any(h in s for h in SKIP_HOSTS) else ""

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")

def qualification(s):
    return "/".join(QUAL.get(p.strip().lower(), p.strip()) for p in clean(s).split("/"))

def modes(s):
    s = s.lower()
    return [m for k, m in (("full", "Full-time"), ("part", "Part-time")) if k in s] or ["Other"]

def delivery(s):
    s = clean(s)
    for k in ("On campus", "Online", "Hybrid"):
        if len(s) < 20 and k.lower() in s.lower():
            return k, ""
    return "Other", s  # long free-text answers are kept as a note

def uni_id(name):
    n = clean(name).lower()
    for k, v in UNI_IDS.items():
        if k in n:
            return v
    sys.exit(f"Unknown university '{name}': add a keyword to UNI_IDS in this script")

def y(v, ind=0):
    pad = " " * ind
    if isinstance(v, list):
        return "[]" if not v else "".join(f"\n{pad}- {json.dumps(i, ensure_ascii=False)}" for i in v)
    return json.dumps(v, ensure_ascii=False)

def main(path):
    rows = list(csv.reader(open(path, encoding="utf-8-sig", newline="")))[1:]
    by_uni = {}
    for r in rows:
        r = r + [""] * (25 - len(r))
        if not clean(r[0]):
            continue
        deliv, deliv_note = delivery(r[3])
        deadline, comments = clean(r[6]), clean(r[7])
        if not deadline and re.search(r"clos|deadline", comments, re.I):
            deadline, comments = comments, ""   # Imperial rows put the deadline in Comments
        prog = clean(r[13])
        c = {"name": clean(r[0]), "qualification": qualification(r[1]), "study_mode": modes(r[2]),
             "delivery": deliv, "delivery_note": deliv_note, "duration": clean(r[4]),
             "dates": clean(r[5]), "deadline": deadline, "notes": comments,
             "summary": clean(r[8]), "subjects": split_list(r[9]), "highlights": bullets(r[10]),
             "careers": split_list(r[11]), "entry_requirements": clean(r[12]),
             "programme_url": url(r[13]), "programme_note": "" if url(r[13]) or not prog else prog,
             "department_url": url(r[14]), "promo_url": url(r[15]), "video_url": url(r[16])}
        c["id"] = slug(c["name"])
        by_uni.setdefault(uni_id(r[17]), []).append(c)
    out = Path("_data/courses"); out.mkdir(parents=True, exist_ok=True)
    keys = ["id", "name", "qualification", "study_mode", "delivery", "delivery_note", "duration", "dates",
            "deadline", "notes", "summary", "subjects", "highlights", "careers", "entry_requirements",
            "programme_url", "programme_note", "department_url", "promo_url", "video_url"]
    for uid, courses in by_uni.items():
        ids = set()
        lines = [f"# Generated by scripts/csv_to_data.py - edit the spreadsheet, then re-run."]
        for c in courses:
            while c["id"] in ids: c["id"] += "-2"
            ids.add(c["id"])
            for i, k in enumerate(keys):
                if k in ("delivery_note", "notes", "programme_note", "department_url", "promo_url", "video_url") and not c[k]:
                    continue
                lines.append(("- " if i == 0 else "  ") + f"{k}: {y(c[k], 4)}")
        (out / f"{uid}.yml").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{uid}: {len(courses)} programmes")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "courses-info.csv")
